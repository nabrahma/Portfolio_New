export function stampSvg(key: string, ink = 'currentColor', accent = 'var(--accent)') {
  const s = stamps[key] ?? stamps.crt;
  let rects = '';
  s.grid.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === '#') rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${ink}"/>`;
      else if (c === '+') rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${accent}"/>`;
    }),
  );
  return `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
